"""주소 기억 — 화면마다 한 번 적은 개발 주소를 다음부터 저절로 채우는지 본다."""
import json
import os
import sys
import tempfile
from pathlib import Path

뿌리 = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(뿌리, "capture-app", "site"))

import 주소기억  # noqa: E402

잰것 = []


def 같나(무엇, 실제, 바람):
    잰것.append((무엇, 실제 == 바람, f"{실제!r} ≠ {바람!r}"))


# 진짜 apps/ 를 건드리지 않게 임시 자리로 옮겨 둔다
임시 = Path(tempfile.mkdtemp())
(임시 / "apps").mkdir()
주소기억.뿌리 = 임시
주소기억.사전파일 = 임시 / "apps" / "주소사전.json"

(임시 / "apps" / "uv.yaml").write_text("""앱이름: 유비스
플랫폼: web
서비스코드: UV
기본주소: https://example.test

화면:
  - 번호: "001"
    이름: 로그인
    디자인이름: 웹_로그인 화면_기본
    주소: /login
""", encoding="utf-8")

# ── 전에 찍은 이름표에 적힌 주소도 기억이다 ──────────────────
같나("이름표에 적힌 주소를 기억한다",
   주소기억.읽기("유비스").get("웹_로그인 화면_기본"), "/login")
같나("다른 서비스 것은 섞이지 않는다", 주소기억.읽기("다른앱"), {})

# ── 적어 두고 다시 채우기 ──────────────────────────────────
초안 = [{"이름": "홈", "디자인이름": "웹_홈_기본", "주소": "/home"},
      {"이름": "공지", "디자인이름": "웹_공지_기본", "주소": ""}]
같나("적힌 주소만 쌓는다", 주소기억.적어두기("유비스", 초안), 1)

새초안 = [{"이름": "홈", "디자인이름": "웹_홈_기본", "주소": ""},
        {"이름": "공지", "디자인이름": "웹_공지_기본", "주소": ""},
        {"이름": "로그인", "디자인이름": "웹_로그인 화면_기본", "주소": ""}]
같나("빈 칸을 기억으로 채운다", 주소기억.채우기("유비스", 새초안), 2)
같나("홈은 기억한 주소로 채워진다", 새초안[0]["주소"], "/home")
같나("이름표에서 읽은 것도 채워진다", 새초안[2]["주소"], "/login")
같나("기억에 없는 화면은 빈 칸 그대로다", 새초안[1]["주소"], "")

사람이적은것 = [{"이름": "홈", "디자인이름": "웹_홈_기본", "주소": "/home2"}]
주소기억.채우기("유비스", 사람이적은것)
같나("사람이 적은 주소는 덮어쓰지 않는다", 사람이적은것[0]["주소"], "/home2")

주소기억.적어두기("유비스", [{"이름": "홈", "디자인이름": "웹_홈_기본", "주소": ""}])
같나("빈 칸으로는 기억을 지우지 않는다", 주소기억.읽기("유비스").get("웹_홈_기본"), "/home")

주소기억.적어두기("유비스", 사람이적은것)
같나("고쳐 적으면 고쳐진다", 주소기억.읽기("유비스").get("웹_홈_기본"), "/home2")

같나("사전 파일은 서비스별로 쌓인다",
   list(json.loads(주소기억.사전파일.read_text(encoding="utf-8"))), ["유비스"])

틀린것 = [(무엇, 말) for 무엇, 됐나, 말 in 잰것 if not 됐나]
for 무엇, 됐나, 말 in 잰것:
    print(("  ✓ " if 됐나 else "  ✗ ") + 무엇 + ("" if 됐나 else f" — {말}"))
print(f"\n{len(잰것) - len(틀린것)}/{len(잰것)} 통과")
sys.exit(1 if 틀린것 else 0)
