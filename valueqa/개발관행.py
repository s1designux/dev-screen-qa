    return (작은["x"] >= 큰["x"] - 여유 and 작은["y"] >= 큰["y"] - 여유
            and 작은["x"] + 작은["w"] <= 큰["x"] + 큰["w"] + 여유
            and 작은["y"] + 작은["h"] <= 큰["y"] + 큰["h"] + 여유)


