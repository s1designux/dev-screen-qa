def _상태말(it, 모든키):
    """이 고침이 어느 상태 화면에서 보였는지 — 다 보이면 굳이 늘어놓지 않는다."""
    상태들 = it.get("상태들") or [it["화면"]["키"]]
    if len(상태들) >= len(모든키) > 1:
        return "모든 상태"
    return ", ".join("`%s`" % k for k in 상태들)


def _묶기(항목들):
    """'무엇을 어떤 값으로' 로 묶는다 — 지금 값이 제각각이어도 바꿀 값이 같으면 한 번에 반영된다.
    화면이 달라도 묶는다(여러 화면을 한 문서로 낼 때 이게 핵심이다)."""
    묶음 = {}
    for it in 항목들:
        for r in it["줄들"]:
            칸 = 묶음.setdefault((r["css"], r["바꿀값"]), {"곳": [], "지금들": []})
            칸["곳"].append(it)
            칸["지금들"].append(r["지금"])
    return 묶음


def _상태이름(정보, 페이지이름):
    """'웹_로그인 화면_비밀번호 숨김 상태' → '비밀번호 숨김 상태' — 페이지 이름은 이미 옆에 있다."""
    이름 = 정보["이름"]
    if 이름 == 페이지이름:
        return "기본"
    앞 = os.path.commonprefix([이름, 페이지이름])
    남은 = 이름[len(앞):].strip("_- ")
    return 남은 or 이름


