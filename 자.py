# -*- coding: utf-8 -*-
"""자(尺) — 좌표는 여기서만 바꾼다.

왜 (river 확정 2026-09-16): 이 시스템에는 자리를 재는 자가 다섯 가지다 —
시안 px / 개발 촬영본 px / 핀 그림의 단위 / 넓은 판 기준 자리 / 화면 기준 자리.
곱하고 나누는 일이 코드 곳곳에 흩어져 있어, 새 기능을 만들 때마다 그중 하나를 잊는다.
(겪은 일 2026-09-16: 홈 화면이 2240px 밀린 채 짝을 찾았고, 나란히 보기가 시안만 1.4배 넓게 잘라 왔다.)

**기준 자는 하나, '화면 기준 px' 이다.** 시안 한 판의 좌표계(예: 360×812, 1920×1080)를 그대로 쓴다.
사람이 시안에서 읽는 값이고, 핀을 비율(%)로 저장하는 축과도 같다.

들어오고 나가는 길은 넷뿐이다:

    개발이 잰 값(판 좌표)  ──잰값_화면()──▶  화면 기준  ──화면_개발그림()──▶ 개발 촬영본 px
    시안 그림 px  ◀──화면_시안그림()──                   ◀──개발그림_화면()──

포털 화면(브라우저)도 **같은 자**를 써야 한다. 그래서 같은 셈을 JS 로 내주는 `JS()` 가 함께 있다 —
파이썬과 자바스크립트가 각자 곱셈을 적지 않게, 원본은 이 파일 하나다.

쓰는 법:
    import 자 as 자모듈
    ㅈ = 자모듈.자(시안폭=1920, 화면폭=1920, 판여백=(-2240, -20), 개발그림폭=1920, 시안그림폭=1920)
    ㅈ.잰값_화면({'x': 2240, 'y': 20, 'w': 100, 'h': 30})   # → {'x': 0, 'y': 0, ...}
"""


def _수(v, 기본=0.0):
    try:
        v = float(v)
    except (TypeError, ValueError):
        return 기본
    return v if v == v else 기본                    # NaN 은 기본값으로


class 자:
    """한 화면의 자. 폭이 빠지면 그 길은 '1배 그대로'가 된다(옛 자료도 깨지지 않게).

    시안폭    시안 한 판의 가로 (화면 기준 px 의 단위)
    화면폭    개발이 잰 화면의 가로 (docW). 없으면 시안폭과 같다고 본다.
    판여백    촬영기가 넓은 판 한가운데에 화면을 앉힌 자리 (contentX, contentY · 음수)
    개발그림폭 개발 촬영본 그림의 가로 px
    시안그림폭 시안 그림의 가로 px
    """

    def __init__(self, 시안폭, 화면폭=None, 판여백=(0, 0), 개발그림폭=None, 시안그림폭=None):
        self.시안폭 = _수(시안폭) or 1.0
        self.화면폭 = _수(화면폭) or self.시안폭
        self.판x, self.판y = _수(판여백[0]), _수(판여백[1])
        self.개발그림폭 = _수(개발그림폭) or self.화면폭
        self.시안그림폭 = _수(시안그림폭) or self.시안폭

    # ── 배율 (한 곳에서만 나눈다) ──────────────────────────────
    @property
    def 잰값배(self):
        """개발이 잰 1px 은 화면 기준 몇 px 인가."""
        return self.시안폭 / self.화면폭

    @property
    def 개발그림배(self):
        """화면 기준 1px 은 개발 촬영본 몇 px 인가."""
        return self.개발그림폭 / self.시안폭

    @property
    def 시안그림배(self):
        """화면 기준 1px 은 시안 그림 몇 px 인가."""
        return self.시안그림폭 / self.시안폭

    # ── 길 넷 ────────────────────────────────────────────────
    def 잰값_화면(self, 상자):
        return self._옮김(상자, self.판x, self.판y, self.잰값배)

    def 화면_개발그림(self, 상자):
        return self._옮김(상자, 0, 0, self.개발그림배)

    def 화면_시안그림(self, 상자):
        return self._옮김(상자, 0, 0, self.시안그림배)

    def 개발그림_화면(self, 상자):
        return self._옮김(상자, 0, 0, 1.0 / self.개발그림배)

    # ── 낱개 값 (길이 하나만 옮길 때) ──────────────────────────
    def 길이_개발그림(self, v):
        return _수(v) * self.개발그림배

    def 길이_시안그림(self, v):
        return _수(v) * self.시안그림배

    @staticmethod
    def _옮김(상자, dx, dy, k):
        if 상자 is None:
            return None
        b = dict(상자)
        b['x'] = (_수(상자.get('x')) + dx) * k
        b['y'] = (_수(상자.get('y')) + dy) * k
        b['w'] = _수(상자.get('w')) * k
        b['h'] = _수(상자.get('h')) * k
        return b

    def 값(self):
        return {'시안폭': self.시안폭, '화면폭': self.화면폭, '판x': self.판x, '판y': self.판y,
                '개발그림폭': self.개발그림폭, '시안그림폭': self.시안그림폭}


def 개발잰값에서(개발meta, 시안폭=None, 개발그림폭=None, 시안그림폭=None):
    """촬영기가 잰 값(`{page}_dev값.json` 의 meta)에서 자를 만든다.

    판 좌표(artboardWidth)가 아니라 **화면 폭(docW)** 을 쓴다 — 넓은 판은 촬영기가 만든 여백일 뿐이다.
    """
    m = 개발meta or {}
    화면폭 = m.get('docW') or m.get('viewportWidth') or m.get('artboardWidth')
    return 자(시안폭=시안폭 or 화면폭, 화면폭=화면폭,
             판여백=(m.get('contentX') or 0, m.get('contentY') or 0),
             개발그림폭=개발그림폭, 시안그림폭=시안그림폭)


# ── 브라우저도 같은 자를 쓴다 ────────────────────────────────────
def JS():
    """포털 화면이 쓰는 같은 자(JavaScript). 셈을 두 번 적지 않으려고 여기서 내준다."""
    return r'''
window.자=window.자||function(o){   // 자(尺) — 파이썬 자.py 와 같은 셈. 곱셈을 다른 데서 적지 않는다.
 const 시안폭=Number(o.시안폭)||1,화면폭=Number(o.화면폭)||시안폭,
       개발그림폭=Number(o.개발그림폭)||화면폭,시안그림폭=Number(o.시안그림폭)||시안폭,
       판x=Number(o.판x)||0,판y=Number(o.판y)||0;
 const 재기=(b,dx,dy,k)=>b?{x:((Number(b.x)||0)+dx)*k,y:((Number(b.y)||0)+dy)*k,
                          w:(Number(b.w)||0)*k,h:(Number(b.h)||0)*k}:null;
 return{잰값배:시안폭/화면폭,개발그림배:개발그림폭/시안폭,시안그림배:시안그림폭/시안폭,
  잰값_화면:b=>재기(b,판x,판y,시안폭/화면폭),
  화면_개발그림:b=>재기(b,0,0,개발그림폭/시안폭),
  화면_시안그림:b=>재기(b,0,0,시안그림폭/시안폭),
  개발그림_화면:b=>재기(b,0,0,시안폭/개발그림폭),
  길이_개발그림:v=>(Number(v)||0)*(개발그림폭/시안폭),
  길이_시안그림:v=>(Number(v)||0)*(시안그림폭/시안폭)};
};
'''


# ── 자체검사 ────────────────────────────────────────────────────
def 점검():
    """자가 제 일을 하는지 — 겪은 일 둘을 그대로 시험으로 둔다."""
    말 = []

    def 같나(a, b, 무엇, 여유=0.001):
        if abs(a - b) > 여유:
            말.append('%s: %s 여야 하는데 %s' % (무엇, b, a))

    # 겪은 일 1 — 홈 화면: 넓은 판(5120) 한가운데 1920 화면. 판의 x=2240 이 화면의 0 이다.
    ㅈ = 개발잰값에서({'docW': 1920, 'artboardWidth': 5120, 'contentX': -2240, 'contentY': -20},
                 시안폭=1920, 개발그림폭=1920, 시안그림폭=1920)
    b = ㅈ.잰값_화면({'x': 2240, 'y': 20, 'w': 100, 'h': 30})
    같나(b['x'], 0, '판 왼쪽 여백 빼기')
    같나(b['y'], 0, '판 위쪽 여백 빼기')
    같나(b['w'], 100, '폭은 그대로')

    # 겪은 일 2 — 앱 화면: 시안 360, 촬영본 1080. 같은 넓이를 잘라야 같은 배율로 보인다.
    ㅈ = 자(시안폭=360, 화면폭=360, 개발그림폭=1080, 시안그림폭=360)
    같나(ㅈ.길이_개발그림(40), 120, '화면 40px 은 촬영본 120px')
    같나(ㅈ.길이_시안그림(40), 40, '화면 40px 은 시안 그림 40px')
    개발 = ㅈ.화면_개발그림({'x': 0, 'y': 100, 'w': 320, 'h': 50})
    다시 = ㅈ.개발그림_화면(개발)
    같나(다시['w'], 320, '개발 그림으로 갔다 와도 같다')
    같나(개발['w'], 960, '화면 320px 은 촬영본 960px')

    # 폭을 모르는 옛 자료는 1배 그대로
    ㅈ = 자(시안폭=1920)
    같나(ㅈ.잰값배, 1.0, '폭을 모르면 1배')
    같나(ㅈ.화면_개발그림({'x': 5, 'y': 5, 'w': 5, 'h': 5})['x'], 5, '폭을 모르면 그대로')

    return 말


if __name__ == '__main__':
    문제 = 점검()
    if 문제:
        for x in 문제:
            print('✗', x)
        raise SystemExit(1)
    print('자 점검 통과 — 판 여백 빼기 · 촬영본 배율 · 되돌리기')
