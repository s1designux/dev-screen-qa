"""시안이 포털의 어느 검수 묶음으로 들어갈지 — **피그마 페이지 = 묶음** (river 확정 2026-09-30).

디자이너는 메뉴별로 피그마 페이지를 나눠 둔다. 프레임 이름은 아직 흐트러져 있어 믿지 않고,
페이지를 그대로 묶음으로 쓴다. 페이지 안의 섹션은 따로 나누지 않고 한 묶음으로 둔다.

페이지 이름에는 작업용 군더더기가 붙어 있다(`GUI_계정_24.11.29` → `계정`).
그것만 떼고, 메뉴 이름으로 보기 어려운 페이지(`Page 1` · `test2` …)나
폰 화면과 웹 화면이 섞인 페이지는 **확인할 것**으로 짚는다 — 사람이 그 자리에서 이름만 고친다.
"""
import re
import unicodedata

# 앞머리 — 디자인 작업 표시일 뿐 메뉴 이름이 아니다.
_앞머리 = re.compile(r"^\s*(?:GUI|UI|UX|WEB|APP|MO|PC|웹|앱|모바일|화면|디자인)\s*[_\-\s·|]+", re.I)
# 꼬리 — 날짜·판 번호.
_날짜 = re.compile(r"[_\-\s·|]*(?:\d{2,4}[.\-/]\d{1,2}(?:[.\-/]\d{1,2})?|\d{6,8})\s*$")
_판 = re.compile(r"[_\-\s·|]*(?:v|ver\.?|rev\.?)\s*\d+(?:\.\d+)*\s*$", re.I)
_앞뒤기호 = re.compile(r"^[\s_\-·|/]+|[\s_\-·|/]+$")

# 메뉴 이름으로 보기 어려운 페이지 이름
_뜻없음 = re.compile(
    r"^(?:page|페이지|untitled|제목\s*없음|test|테스트|temp|tmp|임시|작업\s*중|wip|draft|초안|"
    r"archive|아카이브|보관|old|옛|이전|cover|표지|guide|가이드|components?|컴포넌트|"
    r"playground|scratch|sandbox|연습|참고|ref(?:erence)?|기타|etc|[-=_~.\s]*)\s*\d*$", re.I)


def 다듬기(페이지이름):
    """페이지 이름에서 작업용 앞머리·날짜·판 번호를 뗀다. 다 떼면 비는 경우엔 원래 이름을 둔다."""
    원래 = unicodedata.normalize("NFC", (페이지이름 or "").strip())
    이름 = 원래
    for _ in range(3):                      # `GUI_웹_계정` 처럼 겹친 것도 떼게
        새 = _앞머리.sub("", 이름)
        if 새 == 이름:
            break
        이름 = 새
    for _ in range(3):
        새 = _판.sub("", _날짜.sub("", 이름))
        if 새 == 이름:
            break
        이름 = 새
    이름 = _앞뒤기호.sub("", 이름)
    return 이름 or 원래


def 확인할것(페이지이름, 화면들):
    """사람이 한 번 봐야 하는 까닭 — 없으면 빈 글."""
    이름 = 다듬기(페이지이름)
    if not 이름 or _뜻없음.match(이름):
        return "페이지 이름이 메뉴 이름이 아닌 것 같습니다"
    폭들 = [f.get("폭") or 0 for f in 화면들 if f.get("폭")]
    if 폭들 and min(폭들) < 600 and max(폭들) >= 1000:
        return "폰 화면과 웹 화면이 섞여 있습니다"
    return ""


def 묶음이름(페이지이름, 고친것=None):
    """사람이 고친 이름이 있으면 그것, 없으면 다듬은 페이지 이름."""
    고친 = unicodedata.normalize("NFC", ((고친것 or {}).get(페이지이름) or "").strip())
    return 고친 or 다듬기(페이지이름)


def 나누기(작업):
    """받은 시안을 페이지 차례대로 [{페이지, 이름, 화면들, 확인}] 로 나눈다."""
    고친것 = 작업.get("묶음이름") or {}
    무리 = {}
    for f in 작업.get("고른화면", []):
        무리.setdefault(f.get("페이지", ""), []).append(f)
    차례 = sorted(무리, key=lambda p: min(f.get("페이지차례", 0) for f in 무리[p]))
    return [{"페이지": p, "이름": 묶음이름(p, 고친것), "화면들": 무리[p],
             "확인": "" if 고친것.get(p) else 확인할것(p, 무리[p])} for p in 차례]


if __name__ == "__main__":
    # 스스로 점검 — 실제로 받은 페이지 이름들
    for 원래, 기대 in (("GUI_계정_24.11.29", "계정"), ("GUI_홈_24.11.29", "홈"),
                     ("로그인", "로그인"), ("UI-정산 v2", "정산"), ("웹_마이페이지_20260930", "마이페이지"),
                     ("GUI_24.11.29", "GUI_24.11.29")):
        assert 다듬기(원래) == 기대, (원래, 다듬기(원래), 기대)
    for 원래, 짚나 in (("test2", True), ("Page 1", True), ("작업중", True), ("GUI_계정_24.11.29", False),
                     ("표지", True), ("홈", False)):
        assert bool(확인할것(원래, [])) == 짚나, 원래
    assert 확인할것("홈", [{"폭": 360}, {"폭": 1440}])
    print("묶음 점검 통과")
