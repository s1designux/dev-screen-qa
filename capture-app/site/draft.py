"""찍을 목록 초안 만들기 — 고른 디자인 화면에서 촬영 목록을 자동으로 채운다.

자동으로 채우는 것은 '초안'일 뿐이다. 확정은 사람이 한다(고칠 수 있게 표로 보여 준다).

프레임 이름에서 읽어내는 규칙(위에서부터 먼저 맞는 것 하나):
  1) BUS-AND-002@empty     → 번호 002 · 상태 empty · 이름은 나머지
  2) 002. 노선조회          → 번호 002 · 이름 노선조회
  3) 노선조회 / empty       → 이름 노선조회 · 상태 empty
  4) 로그인 화면_비밀번호 커서 활성화 상태
                          → 상태는 이름의 **마지막 토막**(_ 로 나눈 뒤)
  5) 그 밖                  → 번호는 고른 순서대로 001,002,… · 상태 default
"""
import re

# 스플래시는 앱이 뜨자마자 잠깐 나왔다 사라진다.
# 너무 일찍 찍으면 홈 화면이, 너무 늦게 찍으면 다음 화면이 잡힌다.
# 이 값은 초안에 '기다림 0.1' 로 적히므로 화면에서 눈으로 보고 고칠 수 있다.
스플래시무늬 = re.compile(r"splash|스플래시|스플레시", re.I)
스플래시기다림 = 0.1

try:
    import 동작규칙
except Exception:      # 규칙 파일이 없어도 초안은 만들어진다
    동작규칙 = None

상태낱말 = {"empty": "empty", "빈": "empty", "빈화면": "empty",
        "error": "error", "오류": "error", "에러": "error",
        "loading": "loading", "로딩": "loading",
        "default": "default", "기본": "default"}


def _상태(조각):
    s = 조각.strip().lower()
    return 상태낱말.get(s) or (s if re.fullmatch(r"[a-z0-9가-힣_-]{1,20}", s) else None)


def 뿌리(이름):
    """같은 화면의 상태 변형인지 가리는 이름 앞부분.

    '웹_로그인 화면_비밀번호 숨김' 과 '웹_로그인 화면_버튼 활성화' 는 같은 뿌리다.
    """
    조각 = [t.strip() for t in (이름 or "").split("_") if t.strip()]
    앞머리 = {"웹", "앱", "web", "app", "aos", "ios", "pc", "mo", "mobile"}
    if len(조각) >= 2 and 조각[0].lower() in 앞머리:
        return 조각[1]
    return 조각[0] if 조각 else ""


def 꼬리(이름):
    """상태를 짐작하게 하는 이름 뒷부분 — 동작 칸의 힌트로만 쓴다."""
    조각 = [t.strip() for t in (이름 or "").split("_") if t.strip()]
    return 조각[-1] if len(조각) >= 3 else ""


def _꼬리상태(원본):
    """이름의 마지막 토막을 상태로 쓴다 — '로그인 화면_비밀번호 커서 활성화 상태'.

    토막이 하나뿐이면(그냥 '노선조회') 상태가 아니라 화면 이름이므로 건드리지 않는다.
    """
    조각 = [t.strip() for t in (원본 or "").split("_") if t.strip()]
    if len(조각) < 2:
        return None
    끝 = 조각[-1]
    return 끝 if 1 <= len(끝) <= 40 else None


def 한줄(이름, 순번):
    원본 = (이름 or "").strip()
    이름부 = 원본
    번호 = None
    상태 = None

    m = re.match(r"^[A-Za-z]{2,6}-(?:AND|IOS|WEB)-(\d{3})(?:@([\w가-힣-]+))?\s*(.*)$", 원본)
    if m:
        번호, 상태, 이름부 = m.group(1), _상태(m.group(2) or "default"), (m.group(3) or 원본)
    else:
        m = re.match(r"^(\d{1,3})[.)\]]?\s+(.*)$", 원본)
        if m:
            번호, 이름부 = m.group(1).zfill(3), m.group(2)
        if "@" in 이름부:
            앞, 뒤 = 이름부.split("@", 1)
            if _상태(뒤):
                이름부, 상태 = 앞.strip(), _상태(뒤)
        elif "/" in 이름부:
            앞, 뒤 = 이름부.rsplit("/", 1)
            if _상태(뒤):
                이름부, 상태 = 앞.strip(), _상태(뒤)

    return {
        "번호": 번호 or f"{순번:03d}",
        "이름": 이름부.strip() or 원본,
        "상태": 상태 or _꼬리상태(이름부) or "default",
        "누를것": "-",      # 앱에 그런 글자가 있는지는 알 수 없다. 사람이 적는다.
        "디자인이름": 원본,
    }


def 놓인순서(화면들):
    """디자인 캔버스에 놓인 대로 줄 세운다 — 위 줄부터, 줄 안에서는 왼쪽부터.

    이름으로 걸러 골랐더라도 순서는 '디자인에 그려 둔 차례' 그대로가 되게 한다.
    페이지가 여럿이면 페이지 차례를 먼저 지킨다.
    """
    def 페이지키(f):
        return (f.get("페이지차례", 0), f.get("페이지", ""))

    줄세운것 = []
    for _, 무리 in _묶어(sorted(화면들, key=페이지키), 페이지키):
        남은 = sorted(무리, key=lambda f: (f.get("y", 0), f.get("x", 0)))
        while 남은:
            기준 = 남은[0]
            띠 = max(40, (기준.get("높이") or 0) * 0.5)   # 같은 줄로 볼 세로 폭
            한줄 = [f for f in 남은 if f.get("y", 0) - 기준.get("y", 0) <= 띠]
            남은 = [f for f in 남은 if f not in 한줄]
            줄세운것 += sorted(한줄, key=lambda f: f.get("x", 0))
    return 줄세운것


def _묶어(정렬된것, 키):
    무리, 지금 = [], None
    for f in 정렬된것:
        k = 키(f)
        if 지금 is None or k != 지금[0]:
            지금 = (k, [])
            무리.append(지금)
        지금[1].append(f)
    return 무리


def 만들기(고른화면들):
    """[{id,이름,...}] → 촬영 목록 초안 [{번호,이름,상태,누를것,디자인이름,노드}]"""
    초안 = []
    앞뿌리 = None
    바탕속 = None
    이미틀림 = False      # 이 묶음에서 이미 틀린 비밀번호를 적어 두었나
    누적실패 = 0          # 이 묶음에서 지금까지 로그인을 몇 번 틀렸나
    for i, f in enumerate(놓인순서(고른화면들), 1):
        이름 = f.get("이름", "")
        줄 = 한줄(이름, i)
        줄["노드"] = f.get("id", "")
        줄["디자인그림"] = f.get("디자인그림", "")
        줄["속"] = f.get("속") or []
        이뿌리 = 뿌리(이름)
        줄["화면묶음"] = 이뿌리
        줄["이어서"] = "예" if (앞뿌리 is not None and 이뿌리 == 앞뿌리) else "아니오"
        if 줄["이어서"] == "예":
            줄["누를것"] = "-"          # 같은 화면의 다른 상태 — 다시 들어가지 않는다
            줄["동작"] = (동작규칙.짓기(이름, f.get("속"), 바탕속, 이미틀림, 누적실패)
                       if 동작규칙 else "")
            줄["힌트"] = 꼬리(이름)
        else:
            줄["누를것"] = "-"      # 디자인 이름을 그대로 누르려 하지 않는다
            바탕속 = f.get("속") or []      # 이 묶음의 바탕 화면(글자·아이콘을 여기서 찾는다)
            # 스플래시는 켜자마자 잠깐만 보인다 — 아주 짧게 기다렸다 찍는다.
            줄["동작"] = (f"기다림 {스플래시기다림:g}" if 스플래시무늬.search(이름) else "")
            줄["힌트"] = ""
            이미틀림, 누적실패 = False, 0    # 앱을 껐다 켜므로 적어 둔 것이 사라진다
        # 틀린 비밀번호를 적어 두면 다음 화면은 로그인 단추만 누르면 된다.
        # 맞는 비밀번호를 적는 화면(숨김 상태 등)이 끼면 다시 적어야 한다.
        동작글 = 줄.get("동작") or ""
        if "<틀린비번>" in 동작글:
            이미틀림 = True
        elif "<비번>" in 동작글:
            이미틀림 = False
        if 동작규칙 and re.search(r"탭 로그인", 동작글):
            누적실패 += 동작규칙.실패횟수(꼬리(이름), 누적실패)
        앞뿌리 = 이뿌리
        초안.append(줄)
    return 초안


def 겹친번호(초안):
    """같은 번호+상태가 두 번 나오면 사진 이름이 덮어써진다 — 미리 알려 준다."""
    본 = {}
    겹침 = []
    for r in 초안:
        k = (r.get("번호", ""), r.get("상태", ""))
        if k in 본:
            겹침.append(f"{k[0]}@{k[1]}")
        본[k] = True
    return sorted(set(겹침))
