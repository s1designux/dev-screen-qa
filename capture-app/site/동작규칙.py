"""동작 초안 짓기 — 화면 이름과 디자인 속 글자를 보고 '무엇을 해야 그 상태가 되는지'를 지어낸다.

규칙은 코드 여기저기 흩지 않고 이 파일 한 곳에 모은다(검수 정책 3계층의 기본값 자리).
지어낸 것은 어디까지나 초안이다. 확정은 사람이 한다.

바탕이 되는 것 두 가지:
  1) 화면 이름의 뒷토막 — '비밀번호 커서 활성화 상태', '비밀번호 숨김 해제' …
  2) 디자인 화면 안의 글자·아이콘 이름과 자리 — 플러그인이 같이 보내 준다
"""
import 매체
import re

# 값이 필요한 칸에 넣을 시험용 글자.
# 아이디·비밀번호는 진짜 값을 여기 적지 않는다 — 표식만 적고, 진짜 값은
# 촬영 준비 사이트 ②의 '앱 정보'에 적어 둔 것을 찍기 직전에 넣는다(lib/account.py).
시험값 = {"아이디": "<아이디>", "이메일": "test01@test.com", "이름": "홍길동",
        "휴대전화": "01012345678", "비밀번호": "<비번>", "틀린비밀번호": "<틀린비번>",
        "기본": "test01"}

# 눌러 놓고 화면이 바뀌기를 기다릴 초. 로그인 실패 글은 0.2초 안에 뜬다(재 봄 2026-09-14) —
# 넉넉히 잡되 3초씩 버리지 않는다.
기다릴초 = "1.2"

# 칸 이름 알아보기 (서비스마다 부르는 말이 달라 여러 개를 둔다)
칸낱말 = ["비밀번호", "새 비밀번호", "아이디", "사번", "이메일", "이름", "휴대전화", "인증번호"]

# 로그인 단추에 적히는 말 — 디자인에서 이 중 하나를 찾아 그 글자를 누른다.
로그인단추무늬 = re.compile(r"^(로그인|로그인하기|확인|시작하기|log\s?in|sign\s?in)$", re.I)

# 아이콘 이름에서 '보기/숨김' 단추 찾기
눈무늬 = re.compile(r"eye|visib|보기|숨김|password|pw", re.I)


def _글자들(속):
    return [x for x in (속 or []) if x.get("종류") == "TEXT" and x.get("글자")]


# 칸의 '안내 글자'로 볼 수 있는 모양 — 이것이 아니면 칸으로 치지 않는다.
안내모양 = re.compile(r"입력|주세요|하세요|해 주|을 적|를 적")


def _칸찾기(속, 칸이름):
    """그 칸의 안내 글자를 찾는다 — '비밀번호' → '비밀번호를 입력해 주세요.'

    '비밀번호 찾기' 같은 링크 글자를 칸으로 잘못 잡지 않도록 안내 모양만 받는다.
    """
    for x in _글자들(속):
        g = x["글자"]
        if 칸이름 in g and len(g) <= 40 and 안내모양.search(g):
            return g
    return ""


def _아이콘자리(속):
    """눈 아이콘처럼 글자가 없는 단추의 한가운데 자리(%).

    칸 오른쪽 끝에 붙은 작은 것만 받는다(가운데 큰 덩어리를 아이콘으로 착각하지 않게).
    """
    for x in 속 or []:
        if x.get("종류") == "TEXT" or not 눈무늬.search(x.get("이름", "")):
            continue
        자 = x.get("자리") or {}
        if not 자:
            continue
        가운데x = 자["x"] + 자["w"] / 2
        if 자["w"] <= 20 and 자["h"] <= 12 and 가운데x >= 55:
            return (round(가운데x), round(자["y"] + 자["h"] / 2))
    return None


칸무늬 = re.compile(r"input|field|textbox|text-?field|입력", re.I)


def _칸상자(속, 안내글):
    """안내 글자를 품고 있는 입력 칸의 상자(%)를 찾는다."""
    글자자리 = None
    for x in _글자들(속):
        if x["글자"] == 안내글:
            글자자리 = x.get("자리")
            break
    if not 글자자리:
        return None
    후보 = []
    for x in 속 or []:
        if x.get("종류") == "TEXT":
            continue
        자 = x.get("자리") or {}
        if not 자 or not 칸무늬.search(x.get("이름", "")):
            continue
        안에 = (자["y"] <= 글자자리["y"] + 1 and 자["y"] + 자["h"] >= 글자자리["y"] and
              자["x"] <= 글자자리["x"] + 1)
        if 안에:
            후보.append(자)
    if not 후보:
        return None
    return min(후보, key=lambda z: z["w"] * z["h"])     # 가장 작게 감싼 것


def _로그인단추(속):
    """디자인에 그려진 로그인 단추의 글자. 못 찾으면 '로그인' 으로 둔다.

    서비스마다 '로그인 / 확인 / Sign in' 처럼 다르게 적는다.
    """
    for x in _글자들(속):
        g = x["글자"].strip()
        if 로그인단추무늬.match(g):
            return g
    return "로그인"


# ── 이름 ↔ 시안 글자 맞추기 (2026-09-15) ──────────────────────────────
# 화면 이름 뒷토막에 든 낱말이 시안 속 단추·입력칸 글자와 같으면 그 글자를 누른다.
# 상태를 나타내는 말(팝업·노출·확장…)은 빼고 남은 낱말로 찾고, 띄어쓰기·따옴표는 지우고 견준다.
누름꼬리 = re.compile(r"노출|확장|펼침|열림|팝업|약관|안내|바텀시트|다이얼로그|드롭다운|메뉴|토글|선택|클릭")
상태말 = re.compile(r"^(팝업|바텀시트|다이얼로그|드롭다운|화면|상태|노출|확장|펼침|열림|닫힘|선택|클릭|탭|메뉴|영역|"
                 r"케이스|case|시|때|후|전|default|기본)$", re.I)
상태꼬리 = re.compile(r"(팝업|바텀시트|노출|확장|펼침|열림|닫힘|화면|상태|메뉴|영역)+$")
# 누를 수 있는 컴포넌트 이름 — 이 안에 든 글자만 '누를 것'으로 친다(제목·설명 글자는 빼려고).
누를컴포넌트 = re.compile(r"BTN|BUTTON|INPUT|FIELD|LINK|SELECT|DROP|COMBO|SEARCH|TAB|CHIP|CARD|MENU|TOGGLE|CHECK|RADIO|"
                     r"단추|버튼|입력|탭", re.I)
# 자료·계정이 그 상태여야 나오는 화면 — 눌러서는 못 만든다(삼성통근버스 시안 402장 중 4할쯤이 이랬다).
자료조건무늬 = re.compile(r"미등록|\d+\s*개\s*등록|등록\s*(?:전|없)|없을|없는|있을|길\s*때|초과|종료|운행 전|게스트|SSO|"
                     r"권한|만료|\d+\s*개|\d+\s*줄|줄 케이스|짧은|경우|승인|거부|대기|일반사용자|관리자|신청 전|신청 후|잔여|미제공")
# 같은 말이 들어 있어도 '단추를 누르는 화면'이면 자료 조건이 아니다 — '승인 요청 버튼 활성화', '등록 팝업 노출'
누름화면 = re.compile(r"버튼|클릭|활성화|입력|탭 시|누름")


def _정규화(글):
    return re.sub(r"[\s\"'‘’“”()\[\]/·,.\-_]", "", 글 or "").lower()


def _상자안(밖, 안, 여유=1.0):
    return (안["x"] >= 밖["x"] - 여유 and 안["y"] >= 밖["y"] - 여유
            and 안["x"] + 안["w"] <= 밖["x"] + 밖["w"] + 여유
            and 안["y"] + 안["h"] <= 밖["y"] + 밖["h"] + 여유)


def _낱말들(꼬리):
    """'버스시간표 다운로드 팝업 노출' → ['버스시간표', '다운로드'] (상태를 나타내는 말은 뺀다)."""
    나온 = []
    for t in re.split(r"[\s_/]+", 꼬리 or ""):
        t = re.sub(r"[\"'‘’“”()\[\]]", "", t)
        if not t or 상태말.match(t):
            continue
        t = 상태꼬리.sub("", t)
        if len(t) >= 2:
            나온.append(_정규화(t))
    return 나온


def _누를곳(속):
    return [x.get("자리") for x in 속 or []
            if x.get("종류") != "TEXT" and x.get("자리") and 누를컴포넌트.search(x.get("이름") or "")]


def _누를안(x, 누를곳):
    """단추·입력칸 컴포넌트 안에 든 요소인가. 조상 이름(사슬)이 있으면 그걸로, 없으면 상자 겹침으로."""
    사슬 = x.get("사슬") or []          # 플러그인은 가까운 조상 4개까지만 싣는다 — 모자라면 상자 겹침으로 본다
    if any(누를컴포넌트.search(n or "") for n in list(사슬) + [x.get("이름") or ""]):
        return True
    자리 = x.get("자리")
    return bool(자리) and any(_상자안(z, 자리) for z in 누를곳)


def _누를글자인가(글, x, 누를곳):
    return bool(x.get("자리")) and 0 < len(글) <= 30 and "\n" not in 글 and _누를안(x, 누를곳)


def _px(x):
    """px 상자가 있으면 그것을, 없으면 %자리를(같은 크기 화면끼리는 그대로 견줄 수 있다)."""
    return x.get("상자") or x.get("자리") or {}


def 이름으로누를것(꼬리, 속):
    """이름의 낱말과 같은 시안 글자. 단추 안 글자를 먼저, 그다음 많이 겹치는 것. 없으면 빈 글자."""
    낱말 = _낱말들(꼬리)
    if not 낱말:
        return ""
    누를곳 = _누를곳(속)
    최고 = None
    for x in _글자들(속):
        g = x["글자"].strip()
        if not g or len(g) > 30 or "\n" in g:
            continue
        ng = _정규화(g)
        점수 = sum(len(w) for w in 낱말 if w in ng or (len(ng) >= 2 and ng in w))
        if not 점수:
            continue
        키 = (1 if _누를글자인가(g, x, 누를곳) else 0, 점수, -len(g))
        if 최고 is None or 키 > 최고[0]:
            최고 = (키, g)
    return 최고[1] if 최고 else ""


def 새로생긴덩어리(바탕, 상태):
    """상태 화면에만 새로 생긴 덩어리(열린 목록·펼친 메뉴)를 찾고, 그 바로 위에 있는 누를 것을 짚는다.

    돌려주는 것: (동작, 근거) 또는 None.
    1) 이름+글자가 같은 요소는 바탕에도 있는 것으로 치고, 상태에만 남는 요소를 '새 것'으로 모은다
       (같은 글자가 바탕보다 더 많이 있으면 남는 만큼이 새 것 — 셀렉박스 값과 열린 목록의 첫 줄이 같아도 된다).
    2) 새 글자를 가장 많이 품은 상자를 덩어리로 본다.
    3) 덩어리 머리(윗변)에 아랫변이 닿아 있고 가로로 겹치는 누를 글자 — 셀렉박스·입력칸 — 를 짚는다.
    팝업처럼 가운데 떠서 위에 아무것도 없는 것은 짚지 않는다(이름 규칙이나 그림에서 고르기로 넘긴다).
    """
    if not 바탕 or not 상태:
        return None
    # 문턱(-6~40px)은 px 기준이다 — px 상자가 없는 옛 꾸러미(%자리뿐)에는 이 규칙을 쓰지 않는다.
    if not (바탕[0].get("상자") and 상태[0].get("상자")):
        return None
    import collections
    바탕키 = collections.Counter((x.get("이름") or "", x.get("글자") or "") for x in 바탕)
    남은 = collections.Counter(바탕키)
    새것 = []
    for x in 상태:
        k = (x.get("이름") or "", x.get("글자") or "")
        if 남은.get(k, 0) > 0:
            남은[k] -= 1
        else:
            새것.append(x)
    새글자 = [x for x in 새것 if x.get("종류") == "TEXT" and x.get("글자") and _px(x)]
    if len(새글자) < 2:
        return None
    # 덩어리 — 새 글자를 가장 많이 품은(같으면 더 작은) 상자
    최고 = None
    for x in 새것:
        if x.get("종류") == "TEXT" or not _px(x):
            continue
        b = _px(x)
        품음 = sum(1 for t in 새글자 if _상자안(b, _px(t), 여유=2))
        if 품음 < max(2, len(새글자) * 0.6):
            continue
        키 = (품음, -(b["w"] * b["h"]))
        if 최고 is None or 키 > 최고[0]:
            최고 = (키, b)
    if 최고 is None:
        return None
    덩 = 최고[1]
    # 덩어리 머리 바로 위에 붙은 누를 글자
    누를곳 = _누를곳(상태)
    후보 = []
    for x in _글자들(상태):
        g = x["글자"].strip()
        if not _누를글자인가(g, x, 누를곳):
            continue
        if not 바탕키.get((x.get("이름") or "", g), 0):     # 누르기 전에도 있던 것이어야 누를 수 있다
            continue
        b = _px(x)
        if _상자안(덩, b, 여유=2):                         # 덩어리 안의 글자는 아니다
            continue
        아랫변 = b["y"] + b["h"]
        틈 = 덩["y"] - 아랫변
        겹침 = min(덩["x"] + 덩["w"], b["x"] + b["w"]) - max(덩["x"], b["x"])
        if 겹침 <= 0 or 틈 < -6 or 틈 > 40:
            continue
        후보.append(((abs(틈), -겹침), g))
    if not 후보:
        # 상태 화면에서 못 찾으면 바탕 화면에서 찾는다 — 입력칸은 글자를 치는 순간 안내 글자가 사라져
        # 상태 시안에는 '동탄' 같은 새 글자만 남는다. 두 화면의 세로 어긋남(스크롤)은 같은 요소끼리 재어 맞춘다.
        dy = _세로어긋남(바탕, 상태)
        if dy is not None:
            바탕누를곳 = _누를곳(바탕)
            for x in _글자들(바탕):
                g = x["글자"].strip()
                if not _누를글자인가(g, x, 바탕누를곳):
                    continue
                b = _px(x)
                아랫변 = b["y"] + b["h"] + dy
                틈 = 덩["y"] - 아랫변
                겹침 = min(덩["x"] + 덩["w"], b["x"] + b["w"]) - max(덩["x"], b["x"])
                if 겹침 <= 0 or 틈 < -6 or 틈 > 40:
                    continue
                후보.append(((abs(틈), -겹침), g))
    if not 후보:
        return None
    후보.sort()
    g = 후보[0][1]
    return (f"탭 {g} → 기다림 {기다릴초}", f"오른쪽에 새로 생긴 덩어리(글자 {len(새글자)}개) 바로 위의 '{g}'")


def _세로어긋남(바탕, 상태):
    """두 화면에서 같은 요소(이름+글자가 같고 한 번씩만 나오는 것)의 세로 차이 가운데값(px). 못 재면 None."""
    import collections, statistics
    def 한번씩(목록):
        c = collections.Counter((x.get("이름") or "", x.get("글자") or "") for x in 목록)
        return {(x.get("이름") or "", x.get("글자") or ""): x for x in 목록
                if c[(x.get("이름") or "", x.get("글자") or "")] == 1 and x.get("글자")}
    a, b = 한번씩(바탕), 한번씩(상태)
    차 = [_px(b[k])["y"] - _px(a[k])["y"] for k in a if k in b and _px(a[k]) and _px(b[k])]
    return statistics.median(차) if len(차) >= 3 else None


def 자료조건인가(이름):
    """뒷토막이 '자료·계정이 그 상태여야 나오는 화면'이면 그 말을, 아니면 빈 글자를 돌려준다.

    이런 화면은 어떤 동작으로도 못 만든다 — 목록에서 미리 알려 헛수고를 막는 데만 쓴다.
    """
    조각 = [t.strip() for t in (이름 or "").split("_") if t.strip()]
    꼬리 = 조각[-1] if len(조각) >= 2 else ""
    if 누름꼬리.search(꼬리) or 누름화면.search(꼬리):
        return ""
    m = 자료조건무늬.search(꼬리)
    return m.group(0) if m else ""


def 누를것들(속, 유형=None, 넓게=False):
    """그림 위에서 고르게 할 '누를 수 있는 것' — [{글자, 자리(%), 동작}].

    `넓게=False` — 단추·입력칸 컴포넌트 안에 든 글자만. 자동으로 짚을 때 쓴다(제목을 짚지 않게).
    `넓게=True`  — 짧은 글자는 다 내준다. **사람이 고르는 창**에서 쓴다(river 확정 2026-09-16):
        시안에서 `회원가입`·`아이디 찾기`·`전체 동의하기` 처럼 단추 이름이 안 붙은 글자가
        실제로는 눌러 들어가는 자리라, 좁게 보면 고를 것이 아예 없는 화면이 생긴다.
    글자 없는 작은 단추는 앱에서만 자리로 누른다(웹은 세로%로 누르지 않는다 — 유형표 `좌표.세로퍼센트`).
    """
    누를곳 = _누를곳(속)
    나온, 본 = [], set()
    for x in _글자들(속):
        g = x["글자"].strip()
        자 = x.get("자리")
        받음 = (bool(자) and 0 < len(g) <= 30 and "\n" not in g) if 넓게 else _누를글자인가(g, x, 누를곳)
        if not 받음:
            continue
        동작 = f"탭 {g}"
        if 동작 in 본:
            continue
        본.add(동작)
        나온.append({"글자": g, "자리": 자, "동작": 동작})
    if 매체.값(유형, "좌표.세로퍼센트", True):
        for x in 속 or []:
            자 = x.get("자리")
            if x.get("종류") == "TEXT" or not 자 or not 누를컴포넌트.search(x.get("이름") or ""):
                continue
            if 자["w"] > 60 or 자["h"] > 25:            # 카드·목록 덩어리는 빼고 작은 단추만
                continue
            if any(_상자안(자, n["자리"]) for n in 나온):   # 이미 글자로 누를 수 있는 것
                continue
            cx, cy = round(자["x"] + 자["w"] / 2), round(자["y"] + 자["h"] / 2)
            나온.append({"글자": (x.get("이름") or "").split("/")[-1], "자리": 자, "동작": f"탭좌표 {cx},{cy}"})
    return 나온


# ── 들머리 짚기 · 켜진 것 견주기 (2026-09-16 river 확정) ──────────────
# 여태 규칙은 **같은 묶음 안의 상태 변형**만 지을 줄 알았다. 묶음이 바뀌는 자리(로그인 → 회원 가입)와
# 체크를 켜야 단추가 켜지는 자리는 늘 빈 칸이었다. 둘 다 '짚는 것'이고 확정은 사람이 한다.

켜짐컴포넌트 = re.compile(r"CHECK|CHK|RADIO|TOGGLE|SWITCH|SELECT-CONTROL|체크|토글", re.I)
전체말 = re.compile(r"전체|모두|전부|all", re.I)


def 들머리짓기(묶음이름, 앞속, 근거=None):
    """새 묶음의 첫 장 — **앞 화면**에서 묶음 이름과 같은 글자를 찾아 그것을 누른 것으로 짚는다.

    '회원 가입' 묶음의 첫 장은 로그인 화면의 `회원가입` 을 눌러 들어간다(띄어쓰기는 무시).
    이름이 통째로 맞을 때만 받는다 — 낱말 하나만 겹치는 글자는 엉뚱한 곳을 짚기 쉽다.
    """
    목표 = _정규화(묶음이름)
    if not 앞속 or len(목표) < 2:
        return ""
    누를곳 = _누를곳(앞속)
    최고 = None
    for x in _글자들(앞속):
        g = x["글자"].strip()
        if not g or len(g) > 30 or "\n" in g:
            continue
        ng = _정규화(g)
        if not ng or (목표 not in ng and ng not in 목표):
            continue
        키 = (1 if _누를글자인가(g, x, 누를곳) else 0, -abs(len(ng) - len(목표)), -len(ng))
        if 최고 is None or 키 > 최고[0]:
            최고 = (키, g)
    if not 최고:
        return ""
    g = 최고[1]
    if isinstance(근거, dict):
        근거["근거"] = f"앞 화면에 묶음 이름과 같은 글자 '{g}'"
    return f"탭 {g} → 기다림 {기다릴초}"


def _켜짐칸들(속):
    """체크·라디오·토글 칸마다 [상자, 그 안에 든 것 수]. 켜지면 안에 체크 표시가 하나 더 생긴다."""
    칸 = [x for x in 속 or [] if x.get("종류") != "TEXT" and _px(x)
          and 켜짐컴포넌트.search(x.get("이름") or "")]
    나온 = []
    for c in 칸:
        b = _px(c)
        큰것 = 40 if c.get("상자") else 8        # px 상자면 40px, %자리뿐이면 8% 까지를 '작은 네모'로 본다
        if not (0 < b.get("w", 0) <= 큰것 and 0 < b.get("h", 0) <= 큰것):
            continue
        속것 = sum(1 for y in 속 or [] if y is not c and _px(y) and _상자안(b, _px(y), 여유=0.3))
        나온.append((b, 속것))
    return 나온


def _오른쪽글자(속, 상자):
    """그 칸 오른쪽에 나란히 붙은 글자 — 체크칸에는 글자가 없어 곁의 이름을 누른다."""
    가운데 = 상자["y"] + 상자["h"] / 2
    틈 = 0.5 if 상자.get("h", 0) < 5 else 2      # %자리면 0.5, px 면 2 만큼 넉넉히 본다
    후보 = []
    for x in _글자들(속):
        b = _px(x)
        if not b or b["x"] < 상자["x"]:
            continue
        if not (b["y"] - 틈 <= 가운데 <= b["y"] + b["h"] + 틈):
            continue
        g = x["글자"].strip()
        if g and len(g) <= 40 and "\n" not in g:
            후보.append((b["x"], g))
    후보.sort()
    return 후보[0][1] if 후보 else ""


def 켜진것견주기(바탕속, 상태속, 근거=None):
    """바탕에 견주어 **새로 켜진 체크·토글**을 찾아 그것을 누른 것으로 짚는다.

    같은 자리의 칸끼리 맞대어, 상태 쪽에 든 것이 더 많으면 켜진 것으로 본다(체크 표시가 생겼다).
    한 번에 켜는 '전체 동의하기' 가 있으면 그것 한 번, 없으면 켜진 것들을 차례로 누른다.
    """
    if not 바탕속 or not 상태속:
        return ""
    바탕칸 = _켜짐칸들(바탕속)
    if not 바탕칸:
        return ""
    켜진 = []
    for b, 셈 in _켜짐칸들(상태속):
        여유 = 2 if 상태속[0].get("상자") else 0.5     # px 면 2px, %면 0.5%
        짝 = [(a, n) for a, n in 바탕칸
              if abs(a["x"] - b["x"]) <= 여유 and abs(a["y"] - b["y"]) <= 여유]
        if 짝 and 셈 > 짝[0][1]:
            켜진.append(b)
    if not 켜진:
        return ""
    켜진.sort(key=lambda z: z["y"])
    글자 = [_오른쪽글자(상태속, b) for b in 켜진]
    글자 = [g for g in 글자 if g]
    if not 글자:
        return ""
    한번에 = next((g for g in 글자 if 전체말.search(g)), "")
    if isinstance(근거, dict):
        근거["근거"] = (f"체크 {len(켜진)}곳이 켜져 있음"
                    + (f" — '{한번에}' 한 번으로 켜진다" if 한번에 else ""))
    차례 = [f"탭 {한번에}"] if 한번에 else [f"탭 {g}" for g in 글자]
    return " → ".join(차례 + [f"기다림 {기다릴초}"])


def _어느칸(꼬리):
    for 칸 in 칸낱말:
        if 칸 in 꼬리:
            return 칸
    return ""


실패꼬리무늬 = re.compile(r"로그인 시도|유효하지 않은|잘못된|틀린|실패")


def 실패화면인가(이름):
    """이름 뒷토막이 '로그인을 틀려야 나오는 화면' 인가."""
    조각 = [t.strip() for t in (이름 or "").split("_") if t.strip()]
    꼬리 = 조각[-1] if len(조각) >= 2 else ""
    return bool(실패꼬리무늬.search(꼬리))


def 실패횟수(꼬리, 누적):
    """이 화면을 찍으려면 로그인을 몇 번 더 틀려야 하는지.

    '(5회 이상)' 이면 5번이 되게 앞에서 이미 틀린 만큼을 뺀다.
    횟수가 적혀 있지 않으면 한 번이다.
    """
    m = re.search(r"(\d+)\s*회\s*이상", 꼬리 or "")
    if m:
        return max(1, int(m.group(1)) - max(0, 누적))
    return 1


def 짓기(이름, 속, 바탕속=None, 이미틀림=False, 누적실패=0, 유형=None, 근거=None):
    """화면 하나의 동작 초안. 못 지으면 빈 글자를 돌려준다(사람이 적게).

    유형(PC 웹·앱 …)마다 쓸 수 있는 말이 다르다 — 유형표 `lib/매체.py` 가 정한다.
    (웹은 세로%로 누르지 않는다: 시안 높이와 브라우저 창 높이가 달라 그대로 옮겨지지 않는다.)

    이미틀림 = 앞 화면에서 이미 틀린 비밀번호를 적어 두었다는 뜻.
    그러면 다시 적지 않고 로그인 단추만 누른다(그만큼 촬영이 빨라진다).

    글자·아이콘은 **묶음의 첫 화면(바탕)** 에서 찾는다.
    상태 시안에는 안내 글자가 빠져 있는 일이 많기 때문이다
    (예: '커서 활성화' 시안에는 '비밀번호를 입력해 주세요.'가 없다).
    """
    찾을곳 = list(바탕속 or []) + list(속 or [])
    조각 = [t.strip() for t in (이름 or "").split("_") if t.strip()]
    꼬리 = 조각[-1] if len(조각) >= 2 else ""
    if not 꼬리:
        return ""

    칸 = _어느칸(꼬리)
    안내글 = _칸찾기(찾을곳, 칸) if 칸 else ""

    # 1) 숨김 해제 / 보기 — 글자 없는 아이콘이다
    if re.search(r"숨김\s*해제|보기|표시", 꼬리) and not re.search(r"숨김 상태", 꼬리):
        # 웹은 세로%를 쓰지 않는다(창 높이가 시안과 달라 빗나간다). 그 칸을 찾아 안쪽 오른쪽 끝을 누른다.
        if not 매체.값(유형, "좌표.세로퍼센트", True):
            if 안내글:
                return f"탭칸끝 {안내글}"
            return ""
        자리 = _아이콘자리(찾을곳)
        if 자리:
            return f"탭좌표 {자리[0]},{자리[1]}"
        # 아이콘 레이어를 못 찾으면 그 칸의 오른쪽 끝(눈 단추가 붙는 자리)을 쓴다
        상자 = _칸상자(찾을곳, 안내글) if 안내글 else None
        if 상자:
            return (f"탭좌표 {round(상자['x'] + 상자['w'] - 5)},"
                    f"{round(상자['y'] + 상자['h'] / 2)}")
        return ""

    # 2) 커서 활성화 / 포커스 — 그 칸을 누른다
    if re.search(r"커서|포커스|활성화 상태|선택 시|클릭", 꼬리) and 안내글:
        return f"탭 {안내글}"

    # 3) 로그인 실패 — 맞는 비밀번호를 넣으면 로그인이 되어 버려 오류 화면을 못 찍는다.
    #    그래서 여기서는 일부러 틀린 비밀번호를 넣는다.
    if re.search(r"로그인 시도|유효하지 않은|잘못된|틀린|실패", 꼬리):
        아이디안내 = _칸찾기(찾을곳, "아이디")
        비번안내 = _칸찾기(찾을곳, "비밀번호")
        단추 = _로그인단추(찾을곳)
        번 = 실패횟수(꼬리, 누적실패)
        # 한 번 틀리면 칸이 그대로 차 있어도 로그인 단추를 도로 꺼 버리는 화면이 있다.
        # 사람이 비밀번호를 한 글자 건드려 단추를 켜듯이, 누르기 전에 칸을 흔든다.
        깨우기 = (f"칸흔들기 {비번안내}={시험값['틀린비밀번호']}"
               if 비번안내 and 매체.값(유형, "단추.한번틀리면꺼짐", False) else "")
        차례 = []
        if not 이미틀림:                     # 이미 적어 둔 것이 있으면 다시 적지 않는다
            if 아이디안내:
                차례.append(f"입력 {아이디안내}={시험값['아이디']}")
            if 비번안내:
                차례.append(f"입력 {비번안내}={시험값['틀린비밀번호']}")
            if 매체.값(유형, "화면키보드", True):
                차례.append("뒤로")           # 화면 키보드를 닫아 단추가 보이게 (웹에는 키보드가 없다)
        한벌 = ([깨우기] if 깨우기 else []) + [f"탭 {단추}", f"기다림 {기다릴초}"]
        if 번 > 1:
            차례.append(f"되풀이 {번}")        # 뒤에 오는 것을 그만큼 되풀이한다 — 흔들기도 매번
            차례 += 한벌
        else:
            if 이미틀림 and 깨우기:            # 앞 화면에서 이미 틀렸다 = 단추가 꺼져 있다
                차례.append(깨우기)
            차례 += [f"탭 {단추}", f"기다림 {기다릴초}"]
        return " → ".join(차례)

    # 4) 입력 / 숨김 상태 — 그 칸에 시험 글자를 적는다
    if re.search(r"입력|숨김 상태|채움", 꼬리) and 안내글:
        return f"입력 {안내글}={시험값.get(칸, 시험값['기본'])}"

    # 5) 버튼 활성화 — 체크를 켜야 켜지는 화면이 먼저다(약관 동의 …).
    #    그다음 앱은 키보드를 닫아 단추가 보이게, 웹은 두 칸을 채우면 단추가 켜진다.
    if re.search(r"버튼\s*활성|활성화$", 꼬리):
        켜기 = 켜진것견주기(바탕속, 속, 근거) if 바탕속 else ""
        if 켜기:
            return 켜기
        if 매체.값(유형, "화면키보드", True):
            return "뒤로 → 기다림 1"
        아이디안내 = _칸찾기(찾을곳, "아이디")
        비번안내 = _칸찾기(찾을곳, "비밀번호")
        차례 = []
        if 아이디안내:
            차례.append(f"입력 {아이디안내}={시험값['아이디']}")
        if 비번안내:
            차례.append(f"입력 {비번안내}={시험값.get('비밀번호', 시험값['기본'])}")
        return " → ".join(차례 + ["기다림 1"]) if 차례 else "기다림 1"

    # 6) 눌러서 뜨는 것(팝업·메뉴·바텀시트…) — 이름에 든 낱말과 같은 글자를 시안에서 찾아 누른다.
    #    '버스시간표 다운로드 팝업 노출' → 시안 단추 '버스 시간표 다운로드'(띄어쓰기는 무시).
    if 누름꼬리.search(꼬리):
        # 누르는 것은 **바탕 화면**에 있다 — 상태 화면에만 있는 글자('최근 검색' 같은 열린 판의 제목)는
        # 누른 뒤에야 생기는 것이라 여기서 고르지 않는다(바탕이 없을 때만 자기 화면에서 찾는다).
        글자 = 이름으로누를것(꼬리, 바탕속 if 바탕속 else 속)
        if 글자:
            return f"탭 {글자} → 기다림 {기다릴초}"

    # 7) 이름으로 못 지었으면 시안 두 장을 견준다 — 새로 생긴 덩어리(열린 목록) 바로 위의 것을 누른 것으로 짚는다.
    #    짚은 것이지 확정이 아니다 — 근거를 같이 돌려주어 화면에 보이고, 사람이 고친다.
    짚음 = 새로생긴덩어리(바탕속, 속) if 바탕속 else None
    if 짚음:
        if isinstance(근거, dict):
            근거["근거"] = 짚음[1]
        return 짚음[0]

    return ""
