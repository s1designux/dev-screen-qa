"""동작 한 줄을 촬영 도구 명령으로 옮긴다.

사람이 쓰는 말은 다섯 가지뿐이다. 화살표(→)나 세미콜론으로 잇는다.

    탭 로그인                 그 글자를 누른다
    입력 아이디=test01        그 칸을 눌러 (먼저 비우고) 글자를 적는다
    입력 아이디=<아이디>        시험 계정은 표식으로 적는다(진짜 값은 앱 정보에만 둔다)
    기다림 2                  2초 기다린다
    스크롤                    아래로 한 번 굴린다
    뒤로                      뒤로 간다
    지우기                    적은 글자를 지운다
    탭좌표 86,41              글자가 없는 아이콘은 자리(가로%,세로%)로 누른다 (앱 전용 — 유형표 참고)
    탭칸끝 비밀번호            그 칸을 찾아 **안쪽 오른쪽 끝**을 누른다(눈 아이콘). 웹은 이것을 쓴다
    칸흔들기 비밀번호=<틀린비번>  그 칸을 한 글자 건드려 **꺼진 단추를 도로 켠다**(적힌 값은 그대로).
                              로그인을 한 번 틀리면 칸이 차 있어도 단추를 꺼 버리는 화면에 쓴다.
                              칸이 비어 있으면 = 뒤의 값을 다시 적는다. 웹 전용
    되풀이 5                   그 뒤에 오는 것들을 5번 되풀이한다
    있으면탭 취소              그 글자가 있으면 누르고, 없으면 그냥 지나간다
                              (삼성패스 저장 팝업처럼 가끔 끼어드는 것에 쓴다)
"""
import re

import account


class 동작오류(Exception):
    pass


def _따옴표(v):
    return '"' + str(v).replace("\\", "\\\\").replace('"', '\\"') + '"'


def 쪼개기(글):
    if not 글 or 글.strip() in ("-", "없음"):
        return []
    return [t.strip() for t in re.split(r"→|->|;|\n", 글) if t.strip()]


def _자리로누르기(글자, 자리):
    """기억해 둔 자리가 있으면 그 자리를, 없으면 글자를 눌러 준다.

    글자를 찾아 누르면 폰 화면 목록을 통째로 읽느라 한 번에 4.7초가 든다.
    자리를 알면 1.5초다(lib/places.py).
    """
    좌표 = (자리 or {}).get(글자)
    if 좌표:
        return ["- tapOn:", f"    point: {int(round(좌표[0]))}%,{int(round(좌표[1]))}%"]
    return [f"- tapOn: {_따옴표(글자)}"]


def 한마디(마디, 계정=None, 실패=False, 자리=None):
    낱말 = 마디.split(None, 1)
    앞 = 낱말[0]
    뒤 = 낱말[1].strip() if len(낱말) > 1 else ""

    if 앞 in ("탭", "누르기", "클릭"):
        if not 뒤:
            raise 동작오류("무엇을 누를지 적어 주세요 — 예: 탭 로그인")
        return _자리로누르기(뒤, 자리)

    if 앞 in ("있으면탭", "있으면누르기"):
        if not 뒤:
            raise 동작오류("무엇이 있으면 누를지 적어 주세요 — 예: 있으면탭 취소")
        return ["- tapOn:", f"    text: {_따옴표(뒤)}", "    optional: true"]

    if 앞 in ("입력", "적기"):
        if "=" not in 뒤:
            raise 동작오류("어느 칸에 무엇을 적을지 = 로 이어 주세요 — 예: 입력 아이디=test01")
        칸, 값 = 뒤.split("=", 1)
        값 = account.채우기(값.strip(), 계정, 실패)   # <아이디>·<비번> → 적어 둔 시험 계정
        # 앱이 지난번 아이디를 기억해 칸에 미리 적어 두는 일이 많다.
        # 그대로 적으면 'sambus011sambus011' 이 되므로 먼저 비운다.
        return _자리로누르기(칸.strip(), 자리) + ["- eraseText", f"- inputText: {_따옴표(값)}"]

    if 앞 in ("기다림", "대기"):
        초 = re.sub(r"[^0-9.]", "", 뒤) or "1"
        return ["- waitForAnimationToEnd:", f"    timeout: {int(float(초) * 1000)}"]

    if 앞 in ("스크롤", "굴리기"):
        return ["- scroll"]

    if 앞 in ("뒤로", "back"):
        return ["- back"]

    if 앞 in ("탭좌표", "자리탭"):
        수 = re.findall(r"[0-9.]+", 뒤)
        if len(수) != 2:
            raise 동작오류("자리를 가로%,세로% 로 적어 주세요 — 예: 탭좌표 86,41")
        return ["- tapOn:", f"    point: {수[0]}%,{수[1]}%"]

    if 앞 in ("지우기",):
        return ["- eraseText"]

    if 앞 in ("탭칸끝",):
        # 웹 전용이다. 앱에서는 자리(탭좌표)가 그대로 먹히므로 그것을 쓴다.
        raise 동작오류("'탭칸끝' 은 웹에서만 씁니다. 앱에서는 탭좌표 를 쓰세요 — 예: 탭좌표 86,41")

    if 앞 in ("칸흔들기",):
        # 웹 전용이다. 앱은 값을 지웠다 다시 적는 것(입력)으로 같은 일을 한다.
        raise 동작오류("'칸흔들기' 는 웹에서만 씁니다. 앱에서는 입력 으로 다시 적어 주세요")

    raise 동작오류(f"모르는 말입니다 — '{마디}'. 쓸 수 있는 말: 탭 · 있으면탭 · 입력 · 기다림 · 스크롤 · 뒤로 · 지우기 · 탭좌표 · 탭칸끝 · 되풀이")


def 누를글자들(글):
    """이 동작에서 '찾아서 눌러야 하는 글자'만 뽑는다 — 자리를 익힐 대상이다.

    '있으면탭'은 있을 수도 없을 수도 있는 것이라 자리를 외우지 않는다.
    """
    글자들 = []
    for 마디 in 쪼개기(글):
        낱말 = 마디.split(None, 1)
        앞 = 낱말[0]
        뒤 = 낱말[1].strip() if len(낱말) > 1 else ""
        if 앞 in ("탭", "누르기", "클릭") and 뒤:
            글자들.append(뒤)
        elif 앞 in ("입력", "적기") and "=" in 뒤:
            글자들.append(뒤.split("=", 1)[0].strip())
    return 글자들


def 옮기기(글, 계정=None, 실패=False, 자리=None):
    """동작 한 줄 → 촬영 도구 명령 여러 줄.

    '되풀이 5' 가 나오면 그 뒤에 오는 것들을 5번 되풀이한다
    (예: 비밀번호 5회 틀리기 → 되풀이 5 → 탭 로그인 → 기다림 2 → 탭 확인).
    """
    마디들 = 쪼개기(글)
    줄 = []
    i = 0
    while i < len(마디들):
        마디 = 마디들[i]
        낱말 = 마디.split(None, 1)
        if 낱말[0] in ("되풀이", "반복"):
            수 = re.sub(r"[^0-9]", "", 낱말[1] if len(낱말) > 1 else "")
            if not 수 or int(수) < 1 or int(수) > 20:
                raise 동작오류("몇 번 되풀이할지 1~20 사이로 적어 주세요 — 예: 되풀이 5")
            뒤 = 마디들[i + 1:]
            if not 뒤:
                raise 동작오류("되풀이할 것을 뒤에 적어 주세요 — 예: 되풀이 5 → 탭 로그인")
            한벌 = []
            for m in 뒤:
                한벌 += 한마디(m, 계정, 실패, 자리)
            return 줄 + 한벌 * int(수)
        줄 += 한마디(마디, 계정, 실패, 자리)
        i += 1
    return 줄


# 웹에서 쓸 수 있는 말 — 찍는 손(lib/webshot.py)이 아는 말과 같아야 한다.
# 두 곳이 갈라져 있어 목록은 통과했는데 정작 찍을 때 '모르는 말'로 멈춘 적이 있다(2026-09-14).
웹말 = ("탭", "누르기", "클릭", "있으면탭", "있으면누르기", "입력", "적기",
      "기다림", "대기", "스크롤", "뒤로", "지우기", "탭좌표", "자리탭", "탭칸끝", "칸흔들기",
      "되풀이", "반복")


def _웹확인(글):
    for 마디 in 쪼개기(글):
        낱말 = 마디.split(None, 1)
        앞 = 낱말[0]
        뒤 = 낱말[1].strip() if len(낱말) > 1 else ""
        if 앞 not in 웹말:
            return f"모르는 말입니다 — '{마디}'. 쓸 수 있는 말: " + " · ".join(
                ("탭", "있으면탭", "입력", "기다림", "스크롤", "뒤로", "지우기", "탭칸끝",
                 "칸흔들기", "되풀이"))
        if 앞 in ("입력", "적기") and "=" not in 뒤:
            return "어느 칸에 무엇을 적을지 = 로 이어 주세요 — 예: 입력 아이디=test01"
        if 앞 in ("탭칸끝",) and not 뒤:
            return "어느 칸의 끝을 누를지 적어 주세요 — 예: 탭칸끝 비밀번호를 입력해 주세요."
        if 앞 in ("칸흔들기",) and not 뒤:
            return "어느 칸을 건드릴지 적어 주세요 — 예: 칸흔들기 비밀번호를 입력해 주세요.=<틀린비번>"
        if 앞 in ("되풀이", "반복"):
            수 = re.sub(r"[^0-9]", "", 뒤)
            if not 수 or not (1 <= int(수) <= 20):
                return "몇 번 되풀이할지 1~20 사이로 적어 주세요 — 예: 되풀이 5"
    return ""


def 확인(글, 유형=None):
    """쓴 대로 되는지만 미리 본다. 되면 빈 글자, 안 되면 까닭.

    유형마다 쓸 수 있는 말이 다르다(유형표 lib/매체.py) — 웹은 폰 명령으로 옮기지 않으므로 따로 본다.
    """
    try:
        import 매체
        웹 = 매체.웹인가(유형)
    except Exception:
        웹 = 유형 in ("web", "mobile-web")
    if 웹:
        return _웹확인(글)
    try:
        옮기기(글)
        return ""
    except 동작오류 as e:
        return str(e)


# ── 잘못 쓴 동작 고쳐 주기 (river 확정 2026-09-16) ─────────────────────
# 규칙을 외우게 하지 않는다. 틀리게 적으면 혼내는 대신 **"이렇게 쓰신 거죠?"** 하고
# 고친 문장을 내밀고, 사람이 단추를 눌러 받아들인다(확정은 사람이 한다).
# 흔한 실수 넷: 앞뒤가 바뀜(`<1234> 입력`) · `=` 빠짐 · 쓸데없는 꺾쇠 · 말이 조금 다름.

같은말 = {
    "탭": ("탭", "누르기", "누름", "눌러", "눌러줘", "클릭", "클릭하기", "터치", "선택", "tap", "click"),
    "있으면탭": ("있으면탭", "있으면누르기", "있으면클릭", "있으면"),
    "입력": ("입력", "입력하기", "적기", "적어", "적는다", "쓰기", "써넣기", "넣기", "타이핑", "type", "input"),
    "기다림": ("기다림", "대기", "기다리기", "기다려", "wait"),
    "스크롤": ("스크롤", "굴리기", "내리기", "스크롤다운", "scroll"),
    "뒤로": ("뒤로", "뒤로가기", "back"),
    "지우기": ("지우기", "비우기", "삭제", "clear"),
    "탭좌표": ("탭좌표", "자리탭", "좌표탭", "좌표"),
    "탭칸끝": ("탭칸끝", "칸끝탭", "칸끝"),
    "칸흔들기": ("칸흔들기", "흔들기"),
    "되풀이": ("되풀이", "반복", "반복하기"),
}
_거꾸로 = {b.lower(): a for a, v in 같은말.items() for b in v}
표식 = ("<아이디>", "<비번>", "<틀린비번>")     # 시험 계정 자리 — 이 꺾쇠는 그대로 둔다
_따옴표무늬 = re.compile(r'^["\'“”‘’「」『』]+|["\'“”‘’「」『』]+$')


def _제낱말(t):
    """'입력해' · '눌러서' 처럼 조사·꼬리가 붙은 말도 알아본다."""
    t = t.strip().strip(",").strip()
    낮 = t.lower()
    if 낮 in _거꾸로:
        return _거꾸로[낮]
    for 바른, 들 in 같은말.items():
        for b in 들:
            if 낮.startswith(b) and len(낮) <= len(b) + 3:
                return 바른
    return ""


def _꺾쇠벗기기(값):
    값 = 값.strip()
    if 값 in 표식:
        return 값
    if 값.startswith("<") and 값.endswith(">") and len(값) > 2:
        return 값[1:-1].strip()
    return 값


_안내끝 = re.compile(r"(입력|기입|주세요|하세요|해 주|적어 주)\s*[.!…]*$")
_토씨앞 = re.compile(r"^(에다가|에다|에는|에|을|를|은|는|으로|로)\s*")
_토씨뒤 = re.compile(r"(에다가|에다|에는|에|을|를|은|는)$")


def _칸맞추기(글, 칸이름들):
    """'인증번호 1234' → ('인증번호', '1234'). 시안에 있는 칸 이름을 먼저 본다."""
    글 = 글.strip()
    for 이름 in sorted(칸이름들 or [], key=len, reverse=True):
        이름 = (이름 or "").strip()
        if 이름 and 글.startswith(이름) and len(글) > len(이름):
            return 이름, 글[len(이름):].strip()
    낱말 = 글.rsplit(None, 1)
    if len(낱말) == 2:
        return 낱말[0].strip(), 낱말[1].strip()
    return "", 글                          # 어느 칸인지는 부르는 쪽이 앞뒤를 보고 채운다


def _한마디고치기(마디, 칸이름들):
    마디 = _따옴표무늬.sub("", 마디.strip()).replace(":", " ").strip()
    if not 마디:
        return ""
    낱말 = 마디.split()
    앞 = _제낱말(낱말[0])
    if 앞:
        뒤 = " ".join(낱말[1:]).strip()
    else:
        끝 = _제낱말(낱말[-1]) if len(낱말) > 1 else ""
        if 끝:                              # 앞뒤가 바뀐 것 — '<1234> 입력'
            앞, 뒤 = 끝, " ".join(낱말[:-1]).strip()
        elif "=" in 마디:                    # 말이 통째로 빠진 것 — '아이디=test01'
            앞, 뒤 = "입력", 마디
        elif len(마디) <= 30:                # 글자만 적은 것 — '로그인'
            앞, 뒤 = "탭", 마디
        else:
            return ""

    if 앞 == "입력":
        if "=" in 뒤:
            칸, 값 = 뒤.split("=", 1)
        else:
            칸, 값 = _칸맞추기(뒤, 칸이름들)
        칸, 값 = _따옴표무늬.sub("", 칸.strip()), _꺾쇠벗기기(_토씨앞.sub("", 값.strip()))
        칸 = _꺾쇠벗기기(칸) if 칸 not in 표식 else 칸
        if 칸 and 칸 not in (칸이름들 or ()):
            칸 = _토씨뒤.sub("", 칸).strip() or 칸
        if not 값:
            return ""
        return f"입력 {칸}={값}" if 칸 else f"입력 ={값}"
    if 앞 == "기다림":
        초 = re.sub(r"[^0-9.]", "", 뒤)
        return f"기다림 {초 or '1.2'}"
    if 앞 in ("스크롤", "뒤로", "지우기"):
        return 앞
    if 앞 == "되풀이":
        수 = re.sub(r"[^0-9]", "", 뒤)
        return f"되풀이 {수}" if 수 else ""
    if 앞 == "탭좌표":
        수 = re.findall(r"[0-9.]+", 뒤)
        return f"탭좌표 {수[0]},{수[1]}" if len(수) == 2 else ""
    뒤 = _꺾쇠벗기기(_따옴표무늬.sub("", 뒤))
    return f"{앞} {뒤}" if 뒤 else ""


def 고쳐보기(글, 유형=None, 칸이름들=()):
    """틀리게 쓴 동작 한 줄을 고쳐 본다. 못 고치면 빈 글자.

    고친 결과가 `확인()` 을 통과할 때만 내민다 — 어설픈 제안으로 사람을 헷갈리게 하지 않는다.
    """
    글 = (글 or "").strip()
    if not 글 or not 확인(글, 유형):
        return ""
    고침 = []
    for 마디 in 쪼개기(글):
        하나 = _한마디고치기(마디, 칸이름들)
        if not 하나:
            return ""
        if 하나.startswith("입력 ="):
            # 칸 이름이 빠졌다 — 바로 앞에서 누른 것이 적는 칸이면 그것으로 본다
            # ('탭 인증번호 입력 → <1234> 입력' 처럼 쓰는 사람이 많다). 입력은 누르는 일까지 하므로 앞 탭은 지운다.
            앞탭 = 고침[-1][2:].strip() if 고침 and 고침[-1].startswith("탭 ") else ""
            안내칸 = [c for c in (칸이름들 or []) if _안내끝.search((c or "").strip())]
            칸 = 앞탭 or (안내칸[0] if len(안내칸) == 1 else "")
            if not 칸:
                return ""
            if 앞탭:
                고침.pop()            # 입력은 누르는 일까지 한다 — 앞의 탭은 겹친다
            하나 = "입력 " + 칸 + 하나[3:]
        고침.append(하나)
    새글 = " → ".join(고침)
    if 새글 == 글 or 확인(새글, 유형):
        return ""
    return 새글
